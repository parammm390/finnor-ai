const LOCAL_DATABASE_HOSTS = new Set(["localhost", "127.0.0.1", "::1"])

function isSupabaseDatabaseHost(hostname) {
  return hostname.endsWith(".supabase.com") || hostname.endsWith(".supabase.co")
}

/**
 * Return a node-postgres connection config with deterministic TLS semantics.
 * node-postgres lets URL ssl parameters replace the explicit `ssl` object, so
 * remove them after observing an intentional `sslmode=disable` override.
 */
export function pgConnectionConfig(connectionString) {
  const parsed = new URL(connectionString)
  const sslDisabled = parsed.searchParams.get("sslmode") === "disable"
  for (const parameter of ["sslmode", "sslcert", "sslkey", "sslrootcert"]) {
    parsed.searchParams.delete(parameter)
  }
  const skipSsl = sslDisabled || LOCAL_DATABASE_HOSTS.has(parsed.hostname)
  if (skipSsl) return { connectionString: parsed.toString() }

  return {
    connectionString: parsed.toString(),
    ssl: {
      rejectUnauthorized: true,
      ...(isSupabaseDatabaseHost(parsed.hostname) ? { ca: SUPABASE_ROOT_CA_2021 } : {}),
    },
  }
}
